const keyBytes = (jwk) => Buffer.from(String(jwk.k), 'base64url').length;

test('generate keys', async () => {
  // docs:start manage-keys/generate
  const secret = await jwkGenerateOct(32); // 32 random bytes, for HS256, A256KW or dir
  const p256 = await jwkGenerateEc('P-256');
  const p384 = await jwkGenerateEc('P-384');
  const p521 = await jwkGenerateEc('P-521');
  const secp256k1 = await jwkGenerateEc('secp256k1');
  const ed25519 = await jwkGenerateOkp('Ed25519');
  const x25519 = await jwkGenerateOkp('X25519');
  // docs:end manage-keys/generate
  assert.equal(secret.kty, 'oct');
  assert.equal(keyBytes(secret), 32);
  for (const [key, crv] of [
    [p256, 'P-256'],
    [p384, 'P-384'],
    [p521, 'P-521'],
    [secp256k1, 'secp256k1'],
  ]) {
    assert.equal(key.kty, 'EC');
    assert.equal(key.crv, crv);
    assert.ok(key.d && key.x && key.y, `${crv}: a private key`);
  }
  for (const [key, crv] of [
    [ed25519, 'Ed25519'],
    [x25519, 'X25519'],
  ]) {
    assert.equal(key.kty, 'OKP');
    assert.equal(key.crv, crv);
    assert.ok(key.d && key.x, `${crv}: a private key`);
  }
  assert.equal(p256.alg, undefined, 'a key generated by type names no algorithm');
});

test('generate a key for an algorithm', async () => {
  // docs:start manage-keys/generate-for-alg
  const key = await jwkGenerateForAlg('ES256');
  // key.alg === "ES256": the key can't be used with another algorithm
  // docs:end manage-keys/generate-for-alg
  assert.equal(key.alg, 'ES256');
  assert.equal(key.kty, 'EC');
  assert.equal(key.crv, 'P-256');
});

test('the public half of a key', async () => {
  const privateKey = fixtureJwk('p256');
  // docs:start manage-keys/to-public
  const publicKey = await jwkToPublic(privateKey);
  // publicKey has kty, crv, x and y, and no "d"
  // docs:end manage-keys/to-public
  assert.equal(publicKey.d, undefined);
  assert.deepEqual(publicKey, fixturePublicJwk('p256'));
});

test('PEM import and export', async () => {
  const privateKey = fixtureJwk('p256');
  // docs:start manage-keys/pem
  const privatePem = await jwkToPem(privateKey, 'pkcs8'); // -----BEGIN PRIVATE KEY-----
  const publicPem = await jwkToPem(privateKey, 'spki'); // -----BEGIN PUBLIC KEY-----

  // The PEM label says which structure the block holds.
  const imported = await jwkFromPem(privatePem);
  // docs:end manage-keys/pem
  assert.ok(privatePem.startsWith('-----BEGIN PRIVATE KEY-----\n'));
  assert.ok(publicPem.startsWith('-----BEGIN PUBLIC KEY-----\n'));
  assert.equal(imported.d, privateKey.d);
  assert.equal(imported.x, privateKey.x);
  assert.equal(imported.alg, undefined, 'PEM does not name a JOSE algorithm');
  const importedPublic = await jwkFromPem(publicPem);
  assert.deepEqual(importedPublic, fixturePublicJwk('p256'));
  const sec1 = await jwkToPem(privateKey, 'sec1');
  assert.ok(sec1.startsWith('-----BEGIN EC PRIVATE KEY-----\n'));
});

test('DER import and export', async () => {
  const privateKey = fixtureJwk('p256');
  // docs:start manage-keys/der
  // DER has no label, so the format is always named.
  const der = await jwkToDer(privateKey, 'sec1');
  const imported = await jwkFromDer(der, 'sec1');
  // docs:end manage-keys/der
  assert.ok(der instanceof Uint8Array);
  assert.equal(imported.d, privateKey.d);
  // The wrong format name is an error, not a guess.
  await assert.rejects(jwkFromDer(der, 'pkcs8'), (err) => err instanceof PolyjoseError && err.code === 'InvalidKey');
});

test('RSA public keys in SPKI and PKCS #1', async () => {
  const rsaPublicKey = fixtureJwk('rsa-public');
  // docs:start manage-keys/rsa-public
  const pkcs1Pem = await jwkToPem(rsaPublicKey, 'pkcs1'); // -----BEGIN RSA PUBLIC KEY-----
  const fromPkcs1 = await jwkFromPem(pkcs1Pem);

  const spkiDer = await jwkToDer(rsaPublicKey, 'spki');
  const fromSpki = await jwkFromDer(spkiDer, 'spki');
  // docs:end manage-keys/rsa-public
  assert.ok(pkcs1Pem.startsWith('-----BEGIN RSA PUBLIC KEY-----\n'));
  assert.equal(fromPkcs1.n, rsaPublicKey.n);
  assert.equal(fromSpki.n, rsaPublicKey.n);
  assert.equal(fromSpki.e, 'AQAB');
});

test('an RSA private key is refused with UnsupportedAlgorithm', async () => {
  const rsaPrivateKey = { ...fixtureJwk('rsa-public'), d: RFC7515_A2_D };
  // docs:start manage-keys/rsa-private
  // `rsaPrivateKey` is an RSA JWK with its private exponent "d".
  let code;
  try {
    await jwkParse(rsaPrivateKey);
  } catch (err) {
    if (!(err instanceof PolyjoseError)) throw err;
    code = err.code; // "UnsupportedAlgorithm"
  }
  // docs:end manage-keys/rsa-private
  assert.equal(code, 'UnsupportedAlgorithm');
  // Its public half is accepted.
  const parsed = await jwkParse(fixtureJwk('rsa-public'));
  assert.equal(parsed.kty, 'RSA');
});

test('JWK thumbprints and thumbprint URIs', async () => {
  const key = RFC7638_KEY;
  // docs:start manage-keys/thumbprint
  const thumbprint = await jwkThumbprint(key); // SHA-256 by default
  const uri = await jwkThumbprintUri(key);
  // uri === "urn:ietf:params:oauth:jwk-thumbprint:sha-256:" + thumbprint
  // docs:end manage-keys/thumbprint
  assert.equal(thumbprint, RFC7638_THUMBPRINT, 'RFC 7638 §3.1');
  assert.equal(uri, `urn:ietf:params:oauth:jwk-thumbprint:sha-256:${RFC7638_THUMBPRINT}`, 'RFC 9278 §6');
  assert.equal(await jwkThumbprint(key, 'sha-512').then((t) => t.length), 86);
  await assert.rejects(jwkThumbprint(key, /** @type {any} */ ('sha-1')), (err) => err instanceof PolyjoseError && err.code === 'UnsupportedAlgorithm');
});

test('wipe returned secret bytes', async () => {
  const privateKey = fixtureJwk('p256');
  // docs:start manage-keys/wipe
  const der = await jwkToDer(privateKey, 'pkcs8');
  // ... store or send the key ...
  der.fill(0); // overwrite the private key bytes once you're done
  // docs:end manage-keys/wipe
  assert.ok(der.length > 0);
  assert.ok(der.every((b) => b === 0));
});
